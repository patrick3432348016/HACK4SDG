import Foundation

// Server rows from supabase/migrations/001_init.sql. Preserve snake_case field names. Foundation only.

/// profiles.avatar：{"mobility","color","skin","age"}。
struct AvatarJSON: Codable, Equatable, Sendable {
    var mobility: String?
    var color: Int?
    var skin: Int?
    var age: String?
}

/// Upsert the current user's profile by ID; server functions restrict block/floor to mutual neighbors.
struct ProfileUpsert: Codable, Equatable, Sendable {
    var id: String
    var nickname: String
    var avatar: AvatarJSON
    var tile_x: Int
    var tile_y: Int
    var community_name: String?
    var block: String?
    var floor: Int?
    var streak: Int
    var streak_day: String?
    var lang: String = "zh-HK"
}

/// community_board(): real users in the surrounding 3×3 grids, without block/floor.
struct BoardRow: Codable, Equatable, Sendable {
    var id: String
    var nickname: String
    var avatar: AvatarJSON?
    var streak: Int
    var month_steps: Int?
    var is_me: Bool
    var is_neighbor: Bool
    var daily_line: String?
}

/// my_neighbors(): mutual neighbors. out_at is their outing landmark only when their send and my receive settings permit it.
struct NeighborRow: Codable, Equatable, Sendable {
    var id: String
    var nickname: String
    var avatar: AvatarJSON?
    var block: String?
    var floor: Int?
    var streak: Int?
    var since: Date?
    var send_remind: Bool?
    var receive_remind: Bool?
    var out_at: String?
    var out_since: Date?
    var daily_line: String?
}

/// Peer profile returned after link_neighbor() succeeds.
struct LinkRow: Codable, Equatable, Sendable {
    var id: String
    var nickname: String
    var avatar: AvatarJSON?
    var block: String?
    var floor: Int?
}

struct MeetupRow: Codable, Equatable, Sendable {
    var id: String
    var inviter: String
    var invitee: String
    var at: Date
    var landmark_name: String?
    var reason: String?
    var status: String          // waiting / accepted / declined / done / cancelled / expired
    var updated_by: String?
    var updated_at: Date?
}

struct SignalRow: Codable, Equatable, Sendable {
    var id: Int64
    var from_user: String
    var to_user: String
    var kind: String            // find_ask / find_answer / find_cancel / say / trip / poke
    var payload: JSONValue
    var created_at: Date?
}

/// Insert signals; no updates, and IDs are generated by the server.
struct SignalInsert: Codable, Equatable, Sendable {
    var from_user: String
    var to_user: String
    var kind: String
    var payload: JSONValue
}

struct OutingUpsert: Codable, Equatable, Sendable {
    var user_id: String
    var landmark_name: String?
    var started_at: Date?
    var updated_at: Date
}

struct WalkUpsert: Codable, Equatable, Sendable {
    var user_id: String
    var day: String
    var minutes: Int
    var steps: Int
    var stop_landmarks: [String]
    var daily_line: String?
}

struct ReportInsert: Codable, Equatable, Sendable {
    var id: String
    var user_id: String
    var tile_x: Int
    var tile_y: Int
    var landmark_name: String
    var kind: String            // sunny / no_seat / rough / other
    var raw_text: String?
}

struct ReportFollowUpRow: Codable, Equatable, Sendable {
    var id: String
    var follow_up: String?
}

/// monthly_report(): landmark × report-kind aggregates with at least ten users, plus nearby walk counts.
struct MonthlyRow: Codable, Equatable, Sendable {
    var landmark_name: String
    var kind: String
    var people: Int
    var walk_count: Int
    var walkers: Int
}

// Explicitly encode null for optional fields: an omitted upsert field means leave unchanged.
extension ProfileUpsert {
    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(id, forKey: .id)
        try c.encode(nickname, forKey: .nickname)
        try c.encode(avatar, forKey: .avatar)
        try c.encode(tile_x, forKey: .tile_x)
        try c.encode(tile_y, forKey: .tile_y)
        try c.encode(community_name, forKey: .community_name)
        try c.encode(block, forKey: .block)
        try c.encode(floor, forKey: .floor)
        try c.encode(streak, forKey: .streak)
        try c.encode(streak_day, forKey: .streak_day)
        try c.encode(lang, forKey: .lang)
    }
}

extension OutingUpsert {
    /// Always send landmark_name (null on return home). Send started_at only for a new outing, preserving it when the landmark changes.
    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(user_id, forKey: .user_id)
        try c.encode(landmark_name, forKey: .landmark_name)
        try c.encodeIfPresent(started_at, forKey: .started_at)
        try c.encode(updated_at, forKey: .updated_at)
    }
}
